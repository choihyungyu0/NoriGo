class _RouteOverviewPainter extends CustomPainter {
  @override
  void paint(Canvas canvas, Size size) {
    final w = size.width;
    final h = size.height;

    canvas.drawRect(
      Offset.zero & size,
      Paint()..color = const Color(0xFFF3F6F0),
    );

    final roadPaint = Paint()
      ..color = _PlannerColors.white
      ..strokeWidth = 5
      ..strokeCap = StrokeCap.round;

    for (var i = 0; i < 6; i++) {
      final y = h * (0.16 + i * 0.14);
      canvas.drawLine(Offset(0, y), Offset(w, y + math.sin(i) * 10), roadPaint);
    }

    for (var i = 0; i < 5; i++) {
      final x = w * (0.14 + i * 0.20);
      canvas.drawLine(Offset(x, 0), Offset(x + math.cos(i) * 10, h), roadPaint);
    }

    canvas.drawOval(
      Rect.fromLTWH(w * 0.74, -h * 0.18, w * 0.30, h * 0.56),
      Paint()..color = const Color(0xFFC9ECC8).withValues(alpha: 0.78),
    );
    canvas.drawOval(
      Rect.fromLTWH(w * 0.80, h * 0.48, w * 0.35, h * 0.58),
      Paint()..color = const Color(0xFFCFE8FA).withValues(alpha: 0.82),
    );

    final route = Path()
      ..moveTo(w * 0.18, h * 0.26)
      ..cubicTo(w * 0.32, h * 0.10, w * 0.44, h * 0.46, w * 0.57, h * 0.36)
      ..cubicTo(w * 0.75, h * 0.23, w * 0.73, h * 0.72, w * 0.88, h * 0.54);

    _drawDashedPath(
      canvas,
      route,
      Paint()
        ..color = _PlannerColors.purple
        ..strokeWidth = 2.6
        ..style = PaintingStyle.stroke
        ..strokeCap = StrokeCap.round,
    );

    final points = [
      Offset(w * 0.18, h * 0.26),
      Offset(w * 0.40, h * 0.38),
      Offset(w * 0.57, h * 0.36),
      Offset(w * 0.30, h * 0.72),
      Offset(w * 0.88, h * 0.54),
    ];

    for (var i = 0; i < points.length; i++) {
      canvas.drawCircle(points[i], 12, Paint()..color = _PlannerColors.purple);
      final painter = TextPainter(
        text: TextSpan(
          text: '${i + 1}',
          style: const TextStyle(
            color: _PlannerColors.white,
            fontSize: 11,
            fontWeight: FontWeight.w900,
          ),
        ),
        textDirection: TextDirection.ltr,
      )..layout();

      painter.paint(
        canvas,
        Offset(
          points[i].dx - painter.width / 2,
          points[i].dy - painter.height / 2,
        ),
      );
    }
  }

  void _drawDashedPath(Canvas canvas, Path path, Paint paint) {
    for (final metric in path.computeMetrics()) {
      var distance = 0.0;
      const dashLength = 7.0;
      const dashGap = 5.0;

      while (distance < metric.length) {
        final next = math.min(distance + dashLength, metric.length);
        canvas.drawPath(metric.extractPath(distance, next), paint);
        distance = next + dashGap;
      }
    }
  }

  @override
  bool shouldRepaint(covariant CustomPainter oldDelegate) => false;
}

