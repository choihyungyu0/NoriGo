  @override
  Widget build(BuildContext context) {
    return Column(
      children: List.generate(items.length, (index) {
        return Padding(
          padding: EdgeInsets.only(bottom: index == items.length - 1 ? 0 : 10),
          child: _ItineraryCard(
            item: items[index],
            isFirst: index == 0,
            isLast: index == items.length - 1,
            scale: scale,
          ),
        );
      }),
    );
  }
}

