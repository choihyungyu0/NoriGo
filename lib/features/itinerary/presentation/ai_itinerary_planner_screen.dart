const _headerAsset = 'assets/images/itinerary/itinerary_header_bg.png';

class AiItineraryPlannerScreen extends StatefulWidget {
  const AiItineraryPlannerScreen({
    super.key,
    this.logoAsset = _logoAsset,
    this.headerAsset = _headerAsset,
    this.repository = const MockItineraryRepository(),
  });

  final String logoAsset;
  final String headerAsset;
  final ItineraryRepository repository;

  @override
  State<AiItineraryPlannerScreen> createState() =>
      _AiItineraryPlannerScreenState();
}

class _AiItineraryPlannerScreenState extends State<AiItineraryPlannerScreen> {
  late final ItineraryController _controller;
  int _selectedTimeIndex = 0;

  @override
  void initState() {
    super.initState();
    _controller = ItineraryController(repository: widget.repository);
    _controller.loadPlan();
  }

  @override
  void dispose() {
    _controller.dispose();
    super.dispose();
  }

  Future<void> _savePlan() async {
    final saved = await _controller.savePlan();
    if (!mounted) return;

    ScaffoldMessenger.of(context).showSnackBar(
      SnackBar(
        content: Text(
          saved
              ? 'Itinerary saved locally for now.'
              : _controller.errorMessage ?? 'Unable to save itinerary.',
        ),
      ),
    );
  }

  void _showRouteReason() {
    showModalBottomSheet<void>(
      context: context,
      showDragHandle: true,
      builder: (context) {
        return SafeArea(
          child: Padding(
            padding: const EdgeInsets.fromLTRB(24, 8, 24, 24),
            child: Column(
              mainAxisSize: MainAxisSize.min,
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                const Text(
                  'Why this route?',
                  style: TextStyle(
                    color: _PlannerColors.deepPurple,
                    fontSize: 22,
                    fontWeight: FontWeight.w900,
                  ),
                ),
                const SizedBox(height: 12),
                const Text(
                  'This plan avoids peak crowd times, keeps travel distance '
                  'short, and balances culture, food, shopping, and sunset '
                  'views.',
                  style: TextStyle(
                    color: _PlannerColors.textSub,
                    fontSize: 16,
                    height: 1.42,
                    fontWeight: FontWeight.w500,
                  ),
                ),
                const SizedBox(height: 14),
                Container(
                  width: double.infinity,
                  padding: const EdgeInsets.all(14),
                  decoration: BoxDecoration(
                    color: _PlannerColors.lavender,
                    borderRadius: BorderRadius.circular(8),
                  ),
                  child: const Text(
                    'Later, this explanation will be generated by ennoia '
                    'using KTO OpenAPI data.',
                    style: TextStyle(
                      color: _PlannerColors.deepPurple,
                      fontSize: 14,
                      height: 1.35,
                      fontWeight: FontWeight.w700,
                    ),
                  ),
                ),
              ],
            ),
          ),
        );
      },
    );
  }

  void _handleBottomNavigation(int index) {
    if (index == 1) return;

    final route = switch (index) {
      0 => AppRoutes.home,
      2 => AppRoutes.cultureScan,
      _ => null,
    };

    if (route != null && AppRouter.routes.containsKey(route)) {
      Navigator.of(context).pushReplacementNamed(route);
      return;
    }

    ScaffoldMessenger.of(context).showSnackBar(
      const SnackBar(content: Text('This section will be connected later.')),
    );
  }

  @override
  Widget build(BuildContext context) {
    return AnnotatedRegion<SystemUiOverlayStyle>(
      value: SystemUiOverlayStyle.dark.copyWith(
        statusBarColor: Colors.transparent,
        statusBarIconBrightness: Brightness.dark,
        statusBarBrightness: Brightness.light,
        systemNavigationBarColor: _PlannerColors.white,
      ),
      child: Scaffold(
        backgroundColor: _PlannerColors.white,
        body: SafeArea(
          bottom: false,
          child: LayoutBuilder(
            builder: (context, constraints) {
              final pageWidth = math.min(constraints.maxWidth, 560.0);
              final scale = (pageWidth / 430.0).clamp(0.86, 1.06).toDouble();
              final safeBottom = MediaQuery.paddingOf(context).bottom;
              final navHeight = 76 * scale + safeBottom;
              final saveButtonBottom = navHeight + 12 * scale;

              return Center(
                child: SizedBox(
                  width: pageWidth,
                  child: AnimatedBuilder(
                    animation: _controller,
                    builder: (context, _) {
                      final plan = _controller.plan;

                      if (_controller.isLoading && plan == null) {
                        return const Center(
                          child: CircularProgressIndicator(
                            color: _PlannerColors.purple,
                          ),
                        );
                      }

                      if (plan == null) {
                        return _ErrorState(
                          message:
                              _controller.errorMessage ??
                              'Unable to load itinerary.',
                          onRetry: _controller.loadPlan,
                        );
                      }

                      return Stack(
                        children: [
                          SingleChildScrollView(
                            physics: const BouncingScrollPhysics(),
                            padding: EdgeInsets.fromLTRB(
                              20 * scale,
                              0,
                              20 * scale,
                              navHeight + 92 * scale,
                            ),
                            child: Column(
                              crossAxisAlignment: CrossAxisAlignment.stretch,
                              children: [
                                _ItineraryHeader(
                                  plan: plan,
                                  logoAsset: widget.logoAsset,
                                  headerAsset: widget.headerAsset,
                                  scale: scale,
                                ),
                                _ControlsRow(
                                  dateLabel: plan.dateLabel,
                                  scale: scale,
                                  onWhyPressed: _showRouteReason,
                                ),
                                SizedBox(height: 14 * scale),
                                _TimeChipRow(
                                  times: plan.items
                                      .map((item) => item.time)
                                      .take(5)
                                      .toList(growable: false),
                                  selectedIndex: _selectedTimeIndex,
                                  scale: scale,
                                  onSelected: (index) {
                                    setState(() {
                                      _selectedTimeIndex = index;
                                    });
                                  },
                                ),
                                SizedBox(height: 16 * scale),
                                _ItineraryTimeline(
                                  items: plan.items,
                                  scale: scale,
                                ),
                                SizedBox(height: 12 * scale),
                                _RouteSummaryCard(plan: plan, scale: scale),
                              ],
                            ),
                          ),
                          Positioned(
                            left: 20 * scale,
                            right: 20 * scale,
                            bottom: saveButtonBottom,
                            child: _SavePlanButton(
                              isSaving: _controller.isSaving,
                              scale: scale,
                              onPressed: _savePlan,
                            ),
                          ),
                          Positioned(
                            left: 0,
                            right: 0,
                            bottom: 0,
                            child: _BottomNavigation(
                              selectedIndex: 1,
                              scale: scale,
                              height: navHeight,
                              safeBottom: safeBottom,
                              onChanged: _handleBottomNavigation,
                            ),
                          ),
                        ],
                      );
                    },
                  ),
                ),
              );
            },
          ),
        ),
      ),
    );
  }
}

