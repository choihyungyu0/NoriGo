class _TimeChipRow extends StatelessWidget {
  const _TimeChipRow({
    required this.times,
    required this.selectedIndex,
    required this.scale,
    required this.onSelected,
  });

  final List<String> times;
  final int selectedIndex;
  final double scale;
  final ValueChanged<int> onSelected;

  @override
  Widget build(BuildContext context) {
    return SizedBox(
      height: 46 * scale,
      child: ListView.separated(
        scrollDirection: Axis.horizontal,
        physics: const BouncingScrollPhysics(),
        itemCount: times.length,
        separatorBuilder: (_, _) => SizedBox(width: 10 * scale),
        itemBuilder: (context, index) {
          final selected = index == selectedIndex;
          final time = times[index];

          return InkWell(
            key: ValueKey(selected ? 'selected-time-$time' : 'time-$time'),
            borderRadius: BorderRadius.circular(8),
            onTap: () => onSelected(index),
            child: AnimatedContainer(
              duration: const Duration(milliseconds: 170),
              width: 72 * scale,
              alignment: Alignment.center,
              decoration: BoxDecoration(
                color: selected ? null : _PlannerColors.white,
                borderRadius: BorderRadius.circular(8),
                border: selected
                    ? null
                    : Border.all(color: _PlannerColors.border),
                gradient: selected
                    ? const LinearGradient(
                        colors: [
                          _PlannerColors.purple,
                          _PlannerColors.purpleDark,
                        ],
                      )
                    : null,
                boxShadow: [
                  BoxShadow(
                    color: _PlannerColors.shadow.withValues(alpha: 0.08),
                    blurRadius: 12,
                    offset: const Offset(0, 6),
                  ),
                ],
              ),
              child: Text(
                time,
                style: TextStyle(
                  color: selected
                      ? _PlannerColors.white
                      : _PlannerColors.textSub,
                  fontSize: 18 * scale,
                  fontWeight: FontWeight.w800,
                  height: 1,
                ),
              ),
            ),
          );
        },
      ),
    );
  }
}

